CREATE PROCEDURE [dbo].[PROC_EXTRATO_INCLUIR](    
    
@PCHR_CODBANCO VARCHAR(4), @PCHR_CODAGENCIA VARCHAR(5), @PCHR_CODPRODUTOBANCO VARCHAR(7), @PCHR_NROOPERACAOBANCO VARCHAR(20),     
@PDEC_VALORLANCAMENTO DECIMAL(15,2), @PINT_CODHISTORICO INT, @PDAT_DATALANCAMENTO DATETIME, @PCHR_OBSERVACAO VARCHAR(250),
@PCHR_USUARIO VARCHAR(50), @PINT_CODMOTIVO INT, @PINT_NROSEQUENCIACANCELA SMALLINT = NULL,
@PCHR_NROPROCESSOSEBRAE VARCHAR(10) = NULL, @PDEC_VALORCALCULADO DECIMAL(15,2))  
    
AS BEGIN    
    
BEGIN TRY    

DECLARE @PINT_CODIGOSITUACAO SMALLINT

SELECT @PINT_CODIGOSITUACAO = OPE_CODIGOSITUACAO
FROM OPERACOES
WHERE OPE_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO
AND OPE_CODIGOBANCO = @PCHR_CODBANCO   
AND OPE_CODIGOAGENCIA = @PCHR_CODAGENCIA  
AND OPE_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO  

-- 12/11/2010 - Tratamento dos historicos 32, 34, 35, 36, 37, 43    
-- 17/11/2010 - Tratamento dos historicos 37 e numero de sequencia    
-- 24/11/2010 - Alteração para Honrada através da trigger de inclusao    
-- 13/12/2010 - Alteração para ajustes do Judiciário    
-- 10/12/2012 - Tratamento dos historicos 41 e 44
DECLARE @LINT_SEQUENCIA INT,    
  @LCHR_CODBANCO VARCHAR(4),     
  @LCHR_CODAGENCIA VARCHAR(5),    
  @LCHR_CODPRODUTOBANCO VARCHAR(7),    
  @LCHR_NROOPERACAOBANCO VARCHAR(20),     
  @LCHR_CNPJ VARCHAR(15),    
  @LDEC_VALORHONRADO NUMERIC(15,2),    
  @LDEC_VALORRECUPARADO NUMERIC(15,2),    
  @LDAT_DATAAJUIZAMENTO DATETIME,     
  @LDEC_VALORINICIAL NUMERIC(15,2),    
  @LCHR_NROPROCESSO VARCHAR(25),    
  @LCHR_ACAO VARCHAR(25),    
  @LCHR_COMARCA VARCHAR(40),    
  @LINT_VARA NUMERIC(3,0),     
  @LCHR_TRIBUNAL VARCHAR(5),    
  @LDEC_VALORACORDADO NUMERIC(15,2),    
  @LCHR_FORMAPAGAMENTO CHAR(1),    
  @LDEC_VALORPARCELA NUMERIC(15,2),     
  @LINT_QTDPARCELAS INT,    
  @LDAT_DATAINGRESSO DATETIME,    
  @LCHR_FASEPROCESSUAL VARCHAR(250),    
  @LCHR_STATUS CHAR(1),    
  @LCHR_ADVOGADO VARCHAR(50),     
  @LCHR_DDD VARCHAR(4),    
  @LCHR_TELEFONE VARCHAR(12),    
  @LCHR_EMAIL VARCHAR(40),    
  @LCHR_OBSERVACOES VARCHAR(250),    
  @LDAT_DATASISTEMA DATETIME,    
  @CCHR_STATUSINTEGRACAORM CHAR(1),    
  @LCHR_ERRO VARCHAR(250),    
  @LCHR_CODIGOBANCOCANCELA VARCHAR(4),     
  @LCHR_CODIGOAGENCIACANCELA VARCHAR(5),      
  @LCHR_CODIGOPRODUTOBANCOCANCELA VARCHAR(7),     
  @LCHR_NROOPERACAOBANCOCANCELA VARCHAR(20),     
  @LINT_CODIGOHISTORICOCANCELA SMALLINT,    
  @LDAT_DATALANCAMENTOCANCELA DATETIME,    
  @LINT_NROSEQUENCIACANCELA SMALLINT,    
  @LDAT_DATACANCELAMENTOCANCELA DATETIME,    
  @LDEC_VALOREFETIVOHONRA NUMERIC(15,2),     
  @LDAT_DATAEFETIVAHONRA DATETIME,    
  @LDEC_VALORPREVISTOHONRA NUMERIC(15,2),    
  @LDAT_DATAPREVISTAHONRA DATETIME,    
  @LDEC_VALORACORDADOFINAL NUMERIC(15,2),    
  @LDAT_DATALANCAMENTOCANCELOU DATETIME,    
  @LINT_NROSEQUENCIACANCELOU INTEGER,    
  @LDEC_VALORLANCAMENTOCANCELA NUMERIC(15,2),    
  @LINT_NROSEQUENCIAORIGEM INTEGER,    
  @LDEC_VALORRECUPERADO DECIMAL(15, 2),    
  @LDEC_VALORARECUPERAR DECIMAL(15, 2),    
  @LCHR_NROPROCESSOSEBRAE VARCHAR(10),    
  @LCHR_CODIGOAGENTE VARCHAR(5),    
  @LCHR_PROCESSOPRINCIPAL VARCHAR(1),    
  @LINT_QTDBASECALCULO INT    
    
    
BEGIN TRAN    
    
SELECT @LDAT_DATASISTEMA = (SELECT CTR_DATASISTEMA FROM CONTROLE)    
SELECT @LCHR_ERRO = ''    
SELECT @LDEC_VALORACORDADOFINAL = 0, @LDEC_VALORRECUPARADO = 0, @LDEC_VALORACORDADO = 0,    
    @LDEC_VALORRECUPERADO = 0, @LDEC_VALORARECUPERAR = 0    
    
SELECT @LINT_SEQUENCIA = isnull((SELECT max(EXT_NROSEQUENCIA)      
               FROM EXTRATOS    
         WHERE EXT_CODIGOBANCO = @PCHR_CODBANCO    
         AND EXT_CODIGOAGENCIA = @PCHR_CODAGENCIA    
            AND EXT_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
         AND EXT_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO),0) + 1    
SELECT @LINT_NROSEQUENCIAORIGEM = @LINT_SEQUENCIA    
    
IF (@PINT_CODHISTORICO = 31)    
 BEGIN      
  SELECT @LINT_QTDBASECALCULO = COUNT(*) FROM BASES_CALCULO     
  WHERE BSC_CODIGOBANCO = @PCHR_CODBANCO    
  AND BSC_CODIGOAGENCIA = @PCHR_CODAGENCIA    
  AND BSC_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
  AND BSC_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO    
      
  IF @LINT_QTDBASECALCULO = 0    
  BEGIN    
   RAISERROR ('Honra não permitida. Não existe base de cálculo para esta operação.', 15,1)    
   RETURN    
  END    
     
 END    
    
IF (@PINT_CODHISTORICO = 31 OR @PINT_CODHISTORICO = 32 OR @PINT_CODHISTORICO = 34 OR @PINT_CODHISTORICO = 35     
 OR @PINT_CODHISTORICO = 36 OR @PINT_CODHISTORICO = 37 OR @PINT_CODHISTORICO = 40 OR @PINT_CODHISTORICO = 43
 OR @PINT_CODHISTORICO = 41 OR @PINT_CODHISTORICO = 44)     
 BEGIN    
	 SELECT @CCHR_STATUSINTEGRACAORM = '0'    
	 IF (@PINT_CODHISTORICO = 40)     
	  BEGIN    
		  IF EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
		   WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
		   @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
		   @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
		   @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
		   EXT_DATALANCAMENTO = @PDAT_DATALANCAMENTO AND    
		   @PINT_CODHISTORICO = EXT_CODIGOHISTORICO AND    
		   EXT_DATACANCELA IS NULL )    
		  BEGIN    
			  SELECT @LCHR_ERRO = 'Já existe lançamento nesta data.'    
			  GOTO ERRO_INCLUI_EXTRATO    
		  END    
	  END     
 END     
ELSE      
 BEGIN
	IF (@PINT_CODHISTORICO = 33)
	BEGIN
		IF EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
		WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
		@PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
		@PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
		@PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
		@PINT_CODHISTORICO = EXT_CODIGOHISTORICO AND  
		NOT EXISTS(SELECT 1 FROM EXTRATOS EX
				   WHERE EX.EXT_CODIGOBANCO = EXTRATOS.EXT_CODIGOBANCO
				   AND EX.EXT_CODIGOAGENCIA = EXTRATOS.EXT_CODIGOAGENCIA
				   AND EX.EXT_CODIGOPRODUTOBANCO = EXTRATOS.EXT_CODIGOPRODUTOBANCO
				   AND EX.EXT_NROOPERACAOBANCO = EXTRATOS.EXT_NROOPERACAOBANCO
				   AND EX.EXT_CODIGOBANCO = @PCHR_CODBANCO
				   AND EX.EXT_CODIGOAGENCIA = @PCHR_CODAGENCIA
				   AND EX.EXT_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO
				   AND EX.EXT_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO
				   AND EX.EXT_CODIGOHISTORICO = 45
				   AND EX.EXT_NROSEQUENCIA > EXTRATOS.EXT_NROSEQUENCIA)
					AND NOT EXISTS (SELECT 1 FROM OPERACOES
									INNER JOIN HONRA_AVAL H ON (H.OPE_NROOPERACAO = OPERACOES.OPE_NROOPERACAO AND H.HON_DATAINCLUSAO > EXT_DATAINCLUSAO)
									WHERE OPE_CODIGOBANCO = EXT_CODIGOBANCO
									AND OPE_CODIGOAGENCIA = EXT_CODIGOAGENCIA
									AND OPE_CODIGOPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO
									AND OPE_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO))
		BEGIN    
			SELECT @LCHR_ERRO = 'Já existe lançamento nesta data.'    
			GOTO ERRO_INCLUI_EXTRATO    
		END
	END
	ELSE
	BEGIN
		IF EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
				  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
				  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
				  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
				  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
				  @PDAT_DATALANCAMENTO = EXT_DATALANCAMENTO AND    
				  @PINT_CODHISTORICO = EXT_CODIGOHISTORICO)
		BEGIN    
			SELECT @LCHR_ERRO = 'Já existe lançamento nesta data.'    
			GOTO ERRO_INCLUI_EXTRATO    
		END
	END
	
	SELECT @CCHR_STATUSINTEGRACAORM = '7'
 END    
    
 IF @PINT_CODHISTORICO <> 36     
  BEGIN    
  IF EXISTS(SELECT EXT_NROOPERACAOBANCO FROM EXTRATOS     
      WHERE EXT_CODIGOBANCO = @PCHR_CODBANCO     
      AND EXT_CODIGOAGENCIA = @PCHR_CODAGENCIA    
      AND EXT_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
      AND EXT_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO    
      AND EXT_CODIGOHISTORICO = 32 AND EXT_DATACANCELA IS NULL)    
  BEGIN     
   RAISERROR ('Alteração do histórico não permitida. Operação com Aval Devolvido.', 15,1)    
   RETURN    
  END     
  END    
-- Valida Datas    
    IF (@PINT_CODHISTORICO = 32 OR @PINT_CODHISTORICO = 34 OR @PINT_CODHISTORICO = 35     
 OR @PINT_CODHISTORICO = 36 OR @PINT_CODHISTORICO = 37 OR @PINT_CODHISTORICO = 40 OR @PINT_CODHISTORICO = 43)     
  IF EXISTS(SELECT EXT_NROOPERACAOBANCO FROM EXTRATOS     
      WHERE EXT_CODIGOBANCO = @PCHR_CODBANCO     
      AND EXT_CODIGOAGENCIA = @PCHR_CODAGENCIA    
      AND EXT_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
      AND EXT_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO    
      AND EXT_CODIGOHISTORICO = 31 AND EXT_DATACANCELA IS NULL    
      AND EXT_DATALANCAMENTO > @PDAT_DATALANCAMENTO)    
  BEGIN     
   RAISERROR ('Data do lançamento deve ser maior ou igual a data da Honra de Aval.', 15,1)    
   RETURN    
  END     
-- TRATA ESTORNO DE LANCAMENTO DE DEVOLUÇÃO    
IF  (@PINT_CODHISTORICO = 36)    
 BEGIN     
   IF NOT EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 32 AND    
  EXT_DATACANCELA IS NULL)     
   BEGIN    
   SELECT @LCHR_ERRO = 'Não existe Devolução de Honra, estorno de devolução não permitido.'    
   GOTO ERRO_INCLUI_EXTRATO    
         END    
       ELSE     
   BEGIN    
    
   SELECT @LCHR_CODIGOBANCOCANCELA = EXT_CODIGOBANCO,     
    @LCHR_CODIGOAGENCIACANCELA = EXT_CODIGOAGENCIA,     
    @LCHR_CODIGOPRODUTOBANCOCANCELA = EXT_CODIGOPRODUTOBANCO,     
    @LCHR_NROOPERACAOBANCOCANCELA = EXT_NROOPERACAOBANCO,     
    @LDAT_DATALANCAMENTOCANCELA = EXT_DATALANCAMENTO,     
    @LINT_CODIGOHISTORICOCANCELA = EXT_CODIGOHISTORICO,    
    @LDAT_DATACANCELAMENTOCANCELA = EXT_DATALANCAMENTO,    
    @LINT_NROSEQUENCIACANCELA = EXT_NROSEQUENCIA,    
    @LDAT_DATALANCAMENTOCANCELOU = EXT_DATACANCELOU,    
    @LINT_NROSEQUENCIACANCELOU = EXT_NROSEQUENCIACANCELA    
  FROM EXTRATOS       
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 32 AND    
  EXT_NROSEQUENCIA = @PINT_NROSEQUENCIACANCELA AND EXT_DATACANCELA IS NULL    
    
    
        -- Recupera valor efetivo da honra e valor previsto da honra     
        SELECT @LDEC_VALOREFETIVOHONRA = LEX_VALORLANCAMENTO,    
      @LDAT_DATAEFETIVAHONRA = LEX_DATALANCAMENTO    
  FROM LOG_EXTRATOS    
  WHERE @PCHR_CODBANCO = LEX_CODIGOBANCO AND    
   @PCHR_CODAGENCIA = LEX_CODIGOAGENCIA AND     
   @PCHR_CODPRODUTOBANCO = LEX_CODIGOPRODUTOBANCO AND     
   @PCHR_NROOPERACAOBANCO = LEX_NROOPERACAOBANCO AND     
   LEX_DATALANCAMENTOEXT = @LDAT_DATALANCAMENTOCANCELOU AND              
   LEX_CODIGOHISTORICOEXT = 31 AND    
   LEX_NROSEQUENCIAEXT = @LINT_NROSEQUENCIACANCELOU AND    
   LEX_CODIGOHISTORICO = 31 AND LEX_DATACANCELA IS NULL    
    
        SELECT @LDEC_VALORPREVISTOHONRA = LEX_VALORLANCAMENTO,    
      @LDAT_DATAPREVISTAHONRA = LEX_DATALANCAMENTO    
  FROM LOG_EXTRATOS    
  WHERE @PCHR_CODBANCO = LEX_CODIGOBANCO AND    
   @PCHR_CODAGENCIA = LEX_CODIGOAGENCIA AND     
   @PCHR_CODPRODUTOBANCO = LEX_CODIGOPRODUTOBANCO AND     
   @PCHR_NROOPERACAOBANCO = LEX_NROOPERACAOBANCO AND     
   LEX_DATALANCAMENTOEXT = @LDAT_DATALANCAMENTOCANCELOU AND              
   LEX_CODIGOHISTORICOEXT = 31 AND    
   LEX_NROSEQUENCIAEXT = @LINT_NROSEQUENCIACANCELOU AND    
   LEX_CODIGOHISTORICO = 30 AND LEX_DATACANCELA IS NULL    
  END     
 END    
    
-- TRATA ESTORNO DE LANCAMENTO DE RECUPERACAO DE HONRA DE AVAL    
IF  (@PINT_CODHISTORICO = 43)    
 BEGIN     
   IF NOT EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 40 AND    
  EXT_DATACANCELA IS NULL AND    
  CONVERT(DATE,EXT_DATALANCAMENTO) = CONVERT(DATE,@PDAT_DATALANCAMENTO))    
   BEGIN    
   SELECT @LCHR_ERRO = 'Não existe lancamento de recuperação de aval para esta data.'    
   GOTO ERRO_INCLUI_EXTRATO    
         END    
   ELSE     
   BEGIN    
      SELECT @LCHR_CODIGOBANCOCANCELA = EXT_CODIGOBANCO,     
    @LCHR_CODIGOAGENCIACANCELA = EXT_CODIGOAGENCIA,     
    @LCHR_CODIGOPRODUTOBANCOCANCELA = EXT_CODIGOPRODUTOBANCO,     
    @LCHR_NROOPERACAOBANCOCANCELA = EXT_NROOPERACAOBANCO,     
    @LDAT_DATALANCAMENTOCANCELA = EXT_DATALANCAMENTO,     
    @LINT_CODIGOHISTORICOCANCELA = EXT_CODIGOHISTORICO,    
    @LINT_NROSEQUENCIACANCELA = EXT_NROSEQUENCIA    
  FROM EXTRATOS       
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 40 AND    
  CONVERT(DATE,EXT_DATALANCAMENTO) = CONVERT(DATE,@PDAT_DATALANCAMENTO)    
      
  UPDATE EXTRATOS SET EXT_DATACANCELA = @PDAT_DATALANCAMENTO,    
       EXT_CODIGOHISTORICOCANCELA = @PINT_CODHISTORICO,    
       EXT_DATAATUALIZACAO = getdate(),    
       EXT_USUARIO = @PCHR_USUARIO,    
       EXT_NROSEQUENCIACANCELA = @LINT_SEQUENCIA,
       EXT_CODIGOSITUACAO = @PINT_CODIGOSITUACAO
  WHERE @LCHR_CODIGOBANCOCANCELA = EXT_CODIGOBANCO AND    
   @LCHR_CODIGOAGENCIACANCELA = EXT_CODIGOAGENCIA AND     
   @LCHR_CODIGOPRODUTOBANCOCANCELA = EXT_CODIGOPRODUTOBANCO AND    
   @LCHR_NROOPERACAOBANCOCANCELA = EXT_NROOPERACAOBANCO AND    
   CONVERT(DATE,@LDAT_DATALANCAMENTOCANCELA) = CONVERT(DATE,EXT_DATALANCAMENTO) AND    
   @LINT_CODIGOHISTORICOCANCELA = EXT_CODIGOHISTORICO    
    
  END     
 END    
        
-- TRATA CANCELAMENTO DE HONRA E DEVOLUCAO DE AVAL    
IF  (0 = 34 OR @PINT_CODHISTORICO = 35 OR @PINT_CODHISTORICO = 32 OR @PINT_CODHISTORICO = 37)     
 BEGIN     
 IF NOT EXISTS(SELECT OPE_NROOPERACAOBANCO FROM OPERACOES     
   WHERE @PCHR_CODBANCO = OPE_CODIGOBANCO AND    
   @PCHR_CODAGENCIA = OPE_CODIGOAGENCIA AND     
   @PCHR_CODPRODUTOBANCO = OPE_CODIGOPRODUTOBANCO AND     
   @PCHR_NROOPERACAOBANCO = OPE_NROOPERACAOBANCO AND OPE_CODIGOSITUACAO = 5)    
   BEGIN    
   SELECT @LCHR_ERRO = 'Situação da operação deve ser honrada para cancelamento/devolução/ajuste de Honra.'    
         GOTO ERRO_INCLUI_EXTRATO    
         END    
    
   IF NOT EXISTS(SELECT EXT_DATALANCAMENTO FROM EXTRATOS    
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 31 AND    
  EXT_DATACANCELA IS NULL)    
   BEGIN    
   SELECT @LCHR_ERRO = 'Ultimo Lancamento de Honra não esta ativo cancelamento/devolução/ajuste não permitido.'    
   GOTO ERRO_INCLUI_EXTRATO    
         END    
    ELSE    
  BEGIN    
      SELECT @LCHR_CODIGOBANCOCANCELA = EXT_CODIGOBANCO,     
    @LCHR_CODIGOAGENCIACANCELA = EXT_CODIGOAGENCIA,     
    @LCHR_CODIGOPRODUTOBANCOCANCELA = EXT_CODIGOPRODUTOBANCO,     
    @LCHR_NROOPERACAOBANCOCANCELA = EXT_NROOPERACAOBANCO,     
    @LDAT_DATALANCAMENTOCANCELA = EXT_DATALANCAMENTO,     
    @LINT_CODIGOHISTORICOCANCELA = EXT_CODIGOHISTORICO,    
    @LINT_NROSEQUENCIACANCELA = EXT_NROSEQUENCIA,    
    @LDEC_VALORLANCAMENTOCANCELA = EXT_VALORLANCAMENTO,    
    @LINT_NROSEQUENCIAORIGEM = EXT_NROSEQUENCIAORIGEM    
  FROM EXTRATOS       
  WHERE @PCHR_CODBANCO = EXT_CODIGOBANCO AND    
  @PCHR_CODAGENCIA = EXT_CODIGOAGENCIA AND     
  @PCHR_CODPRODUTOBANCO = EXT_CODIGOPRODUTOBANCO AND     
  @PCHR_NROOPERACAOBANCO = EXT_NROOPERACAOBANCO AND     
  EXT_CODIGOHISTORICO = 31 AND    
  EXT_DATACANCELA IS NULL       
  END             
 END    
    
IF @PINT_CODHISTORICO = 40    
 BEGIN    
  SELECT    
   @LDEC_VALORRECUPERADO = ISNULL(JUA_VALORRECUPERADO, 0)    
  FROM    
   JUDICIARIO_ACOMPANHAMENTO    
  WHERE    
   JUA_CODIGOBANCO = @PCHR_CODBANCO    
   AND JUA_CODIGOAGENCIA = @PCHR_CODAGENCIA    
   AND JUA_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
   AND JUA_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO    
   AND (JUA_NROPROCESSOSEBRAE = @PCHR_NROPROCESSOSEBRAE OR CONVERT(VARCHAR(10),  @PCHR_NROPROCESSOSEBRAE) IS NULL)    
   AND JUA_PROCESSOPRINCIPAL = 'S'    
   AND JUA_SEQUENCIA IN (SELECT MAX(JUA_SEQUENCIA) FROM JUDICIARIO_ACOMPANHAMENTO    
            WHERE JUA_CODIGOBANCO = @PCHR_CODBANCO    
            AND JUA_CODIGOAGENCIA = @PCHR_CODAGENCIA    
            AND JUA_CODIGOPRODUTOBANCO = @PCHR_CODPRODUTOBANCO    
            AND JUA_NROOPERACAOBANCO = @PCHR_NROOPERACAOBANCO    
           AND JUA_PROCESSOPRINCIPAL = 'S'    
           AND (JUA_NROPROCESSOSEBRAE = @PCHR_NROPROCESSOSEBRAE OR CONVERT(VARCHAR(10),  @PCHR_NROPROCESSOSEBRAE) IS NULL))    
      
